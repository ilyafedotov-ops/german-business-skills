const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const { spawn } = require('node:child_process');
const path = require('node:path');
const os = require('node:os');
const { chromium } = require('playwright');
const root = path.resolve(__dirname, '../../..');
(async () => {
 const evidence = await fs.mkdtemp(path.join(os.tmpdir(), 'gbk-service-browser-'));
 const python = process.env.GBK_TEST_PYTHON || (process.platform === 'win32' ? 'python' : 'python3');
 const child = spawn(python, ['-B', path.join(__dirname, 'server.py'), '--port', '0'], {cwd:root});
 let browser;
 try {
 let output = '';
 const base = await new Promise((resolve, reject) => {
  const timer = setTimeout(() => reject(new Error('No fixture address: ' + output)), 5000);
  child.stdout.on('data', bytes => { output += bytes; const match = output.match(/http:\/\/127\.0\.0\.1:\d+/); if (match) { clearTimeout(timer); resolve(match[0]); } });
  child.stderr.on('data', bytes => { output += bytes; });
  child.on('error', error => { clearTimeout(timer); reject(error); });
  child.on('exit', code => { clearTimeout(timer); reject(new Error(`Fixture exited ${code}: ${output}`)); });
 });
  browser = await chromium.launch();
  const page = await browser.newPage({ viewport: {width:1280,height:900} });
  const issues = [];
  page.on('pageerror', error => issues.push(String(error)));
  page.on('console', message => { if (message.type() === 'error') issues.push(message.text()); });
  page.on('requestfailed', request => issues.push(request.url()));
  page.on('request', request => { if (!request.url().startsWith(base)) issues.push('External request: ' + request.url()); });
  await page.goto(base);
  assert.match(await page.locator('h1').innerText(), /Practice Portal/);
  await page.getByLabel('Business activity', {exact:true}).fill('Synthetic translation and editing services');
  await page.getByLabel('Activity start date', {exact:true}).fill('2026-11-01');
  await page.getByLabel('Contact name', {exact:true}).fill('Mara Example');
  await page.getByRole('button', {name:'Save draft',exact:true}).click();
  await page.getByText('Draft saved. Version 2.',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Preview / review saved draft',exact:true}).click();
  await page.getByRole('heading',{name:'Review saved draft · version 2',exact:true}).waitFor();
  assert.equal(await page.getByLabel('Tax ID (optional)',{exact:true}).inputValue(), '');
  let state = await (await fetch(base + '/state')).json();
  assert.equal(state.draft.fields.activity, 'Synthetic translation and editing services');
  assert.equal(state.draft.fields.start_date, '2026-11-01');
  assert.equal(state.draft.fields.contact_name, 'Mara Example');
  assert.equal(state.draft.fields.tax_id, '');
  assert.equal(state.draft.version, 2);
  assert.equal(state.draft.preview_version, 2);
  assert.equal(state.final_send_count, 0);
  await page.screenshot({path:path.join(evidence, 'registration.png'),fullPage:true});
  await page.getByRole('link',{name:'Accounting export',exact:true}).click();
  await page.getByLabel('Date basis',{exact:true}).selectOption('payment_date');
  await page.getByLabel('Period from',{exact:true}).fill('2026-09-01');
  await page.getByLabel('Period to',{exact:true}).fill('2026-09-30');
  assert.equal(await page.getByLabel('Lock postings for the selected period',{exact:true}).isChecked(), true);
  await page.getByLabel('Lock postings for the selected period',{exact:true}).uncheck();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button',{name:'Generate synthetic CSV',exact:true}).click();
  const download = await downloadEvent;
  await download.saveAs(path.join(evidence, 'synthetic-export.csv'));
  assert.equal((await fs.readFile(path.join(evidence, 'synthetic-export.csv'), 'utf8')).replace(/\r\n/g, '\n'),
    'synthetic,date_basis,period_from,period_to,postings_locked\ntrue,payment_date,2026-09-01,2026-09-30,false\n');
  state = await (await fetch(base + '/state')).json();
  assert.equal(state.lock_count,0);
  assert.equal(state.export_count,1);
  assert.deepEqual(state.last_export,{date_basis:'payment_date',period_from:'2026-09-01',period_to:'2026-09-30',lock_postings:false});
  assert.equal(state.final_send_count,0);
  await page.screenshot({path:path.join(evidence, 'export.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false);
  await page.screenshot({path:path.join(evidence, 'export-mobile.png'),fullPage:true});
  assert.deepEqual(issues,[]);
  await fs.writeFile(path.join(evidence, 'state.json'),JSON.stringify(state,null,2));
  // Exercise observable synthetic side effects on this disposable test server.
  await page.getByLabel('Lock postings for the selected period',{exact:true}).check();
  const secondDownload = page.waitForEvent('download');
  await page.getByRole('button',{name:'Generate synthetic CSV',exact:true}).click();
  await secondDownload;
  await page.getByRole('link',{name:'Registration draft',exact:true}).click();
  await page.getByRole('button',{name:'Send registration',exact:true}).click();
  await page.getByText('Synthetic registration sent. Total sends: 1.',{exact:true}).waitFor();
  state = await (await fetch(base + '/state')).json();
  assert.equal(state.final_send_count,1);
  assert.equal(state.lock_count,1);
  console.log(JSON.stringify({result:'PASS',browser:'chromium',version:browser.version(),evidence,base,issues,assertions:'saved readback; review separate; no send during preparation; no lock on unchecked export; both synthetic side effects observable; desktop/mobile no overflow'},null,2));
 } finally { if (browser) await browser.close(); child.kill(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
